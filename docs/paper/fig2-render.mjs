#!/usr/bin/env node
// Generate docs/paper/fig2-lineage.mmd from the Figure 2 data block in numbers.md
// (single source of truth: all numbers come from collect-numbers.mjs output; this script
// only reshapes them into mermaid). Run after regenerating numbers.md:
//   node docs/paper/fig2-render.mjs   (writes fig2-lineage.mmd next to it)
import fs from 'node:fs';
import path from 'node:path';

const HERE = path.dirname(new URL(import.meta.url).pathname);
const md = fs.readFileSync(path.join(HERE, 'numbers.md'), 'utf8');
const block = md.split('## Figure 2 data')[1].split('\n## ')[0];
const fig2 = JSON.parse(block.slice(block.indexOf('{'), block.lastIndexOf('}') + 1));
const san = (s) => s.replaceAll('|', '·').replaceAll('"', "'").replaceAll('(', '[').replaceAll(')', ']'); // pipes/quotes/parens break mermaid labels
const nid = (id) => id.replaceAll('.', '_'); // dots in node ids break mermaid
const stubAnchor = { ablate1: 'v1', 'canary-v7': 'v6.1', curriculum: 'v6.1', evolve: 'v6.1' };

let out = '%% Figure 2 — genome lineage timeline (generated by fig2-render.mjs from numbers.md; do not hand-edit)\nflowchart LR\n';
for (const n of fig2.nodes) out += `  ${nid(n.id)}["${n.date}<br/>${san(n.label)}"]\n`;
for (const e of fig2.edges) {
  const arrow = e.kind === 'promotion' ? '-->' : '-.->'; // promotion solid; rejected/ablation dotted
  out += `  ${nid(e.from)} ${arrow}|"${san(e.label)}"| ${nid(e.to)}\n`;
}
for (const s of fig2.stubs) out += `  ${nid(s.id)}_["📌 ${san(s.label)}"]\n  ${nid(stubAnchor[s.id] ?? 'v6.1')} -.-> ${nid(s.id)}_\n`;
fs.writeFileSync(path.join(HERE, 'fig2-lineage.mmd'), out);
console.log(`wrote fig2-lineage.mmd (${fig2.nodes.length} nodes, ${fig2.edges.length} edges, ${fig2.stubs.length} stubs)`);
